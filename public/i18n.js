export const supportedLanguages=['zh-CN','en-US'];
export function translate(value,language='zh-CN'){
 const text=String(value??'');
 return language==='en-US'?(en[text]??text):text;
}

const originalTextByNode=new WeakMap();
export function localizeTextNodes(root,language='zh-CN'){
 const walker=root.ownerDocument.createTreeWalker(root,4);
 while(walker.nextNode()){
  const node=walker.currentNode,parent=node.parentElement;
  if(!parent||parent.closest('pre,code,textarea,input,td,[data-source-file],[data-source-match],[data-user-content]'))continue;
 if(!parent.matches('h1,h2,h3,h4,a,button,label,th,dt,option,small,strong,p,.hint,.subtle,.tag,.eyebrow,.metric-note,.section-heading span,.footer-tagline,.empty'))continue;
  const original=originalTextByNode.get(node)??node.nodeValue;
  originalTextByNode.set(node,original);
  const trimmed=original.trim(),translated=translate(trimmed,language);
  if(trimmed&&node.nodeValue!==original.replace(trimmed,translated))node.nodeValue=original.replace(trimmed,translated);
 }
}
